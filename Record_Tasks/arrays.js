// JavaScript Program using Arrays

// Create an array of 10 student marks
let marks = [85, 72, 90, 65, 78, 95, 88, 60, 75, 92];

// Display all marks
console.log("Student Marks:");
console.log(marks);

// Display each mark one by one
for (let i = 0; i < marks.length; i++) {
    console.log("Student " + (i + 1) + ": " + marks[i]);
}
